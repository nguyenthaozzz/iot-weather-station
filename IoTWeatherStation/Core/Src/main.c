/**
  * @brief  Function implementing the SensorTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartSensorTask */
void StartSensorTask(void const * argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */
	// Init sensor
	Sensor_Data_t data;
	
	data.bmp180_status = 1;
	data.dht11_status = 1;
	
	HAL_StatusTypeDef status_BMP180 = BMP180_Init();
	HAL_StatusTypeDef status_DHT11 = DHT11_Init();
	
	if(status_BMP180 != BMP180_OK)
		data.bmp180_status = 0;
	if(status_DHT11 != DHT11_OK)
		data.dht11_status = 0;
	
		
  for(;;)
  {
		HAL_StatusTypeDef status;
		status = BMP180_GetData(&data.bmp180);
		if(status != BMP180_OK) data.bmp180_status = 0;
		
		status = DHT11_GetData(&data.dht11);
		if(status != DHT11_OK) 
			data.dht11_status = 0;
		
    osDelay(2000);
  }
  /* USER CODE END 5 */
}

